CREATE TABLE usuario (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome             VARCHAR(120) NOT NULL,
    email            VARCHAR(160) NOT NULL,
    telefone_contato VARCHAR(20),
    criado_em        TIMESTAMP    NOT NULL,
    CONSTRAINT uk_usuario_email UNIQUE (email)
);

CREATE TABLE dispositivo (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id   BIGINT      NOT NULL,
    marca        VARCHAR(60) NOT NULL,
    modelo       VARCHAR(80) NOT NULL,
    imei         VARCHAR(15) NOT NULL,
    operadora    VARCHAR(40),
    numero_linha VARCHAR(20),
    status       VARCHAR(20) NOT NULL,
    criado_em    TIMESTAMP   NOT NULL,
    CONSTRAINT uk_dispositivo_imei UNIQUE (imei),
    CONSTRAINT fk_dispositivo_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id) ON DELETE CASCADE,
    CONSTRAINT ck_dispositivo_status CHECK (status IN ('ATIVO', 'ROUBADO', 'BLOQUEADO', 'RECUPERADO'))
);

CREATE TABLE ocorrencia (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo       VARCHAR(20)      NOT NULL,
    latitude   DOUBLE PRECISION NOT NULL,
    longitude  DOUBLE PRECISION NOT NULL,
    data_hora  TIMESTAMP        NOT NULL,
    descricao  VARCHAR(500),
    usuario_id BIGINT,
    CONSTRAINT fk_ocorrencia_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id) ON DELETE SET NULL,
    CONSTRAINT ck_ocorrencia_tipo CHECK (tipo IN ('FURTO', 'ROUBO', 'TENTATIVA'))
);

CREATE TABLE alerta (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id           BIGINT,
    latitude             DOUBLE PRECISION NOT NULL,
    longitude            DOUBLE PRECISION NOT NULL,
    score                DOUBLE PRECISION NOT NULL,
    nivel                VARCHAR(20)      NOT NULL,
    ocorrencias_proximas INTEGER          NOT NULL,
    mensagem             VARCHAR(500)     NOT NULL,
    criado_em            TIMESTAMP        NOT NULL,
    CONSTRAINT fk_alerta_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id) ON DELETE CASCADE
);

CREATE TABLE incidente (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dispositivo_id BIGINT      NOT NULL,
    ocorrencia_id  BIGINT,
    status         VARCHAR(20) NOT NULL,
    aberto_em      TIMESTAMP   NOT NULL,
    concluido_em   TIMESTAMP,
    CONSTRAINT fk_incidente_dispositivo FOREIGN KEY (dispositivo_id) REFERENCES dispositivo (id) ON DELETE CASCADE,
    CONSTRAINT fk_incidente_ocorrencia FOREIGN KEY (ocorrencia_id) REFERENCES ocorrencia (id) ON DELETE SET NULL
);

CREATE TABLE passo_resposta (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incidente_id  BIGINT      NOT NULL,
    acao          VARCHAR(40) NOT NULL,
    ordem         INTEGER     NOT NULL,
    prazo_minutos INTEGER     NOT NULL,
    concluido     BOOLEAN     DEFAULT FALSE NOT NULL,
    concluido_em  TIMESTAMP,
    CONSTRAINT fk_passo_incidente FOREIGN KEY (incidente_id) REFERENCES incidente (id) ON DELETE CASCADE
);
